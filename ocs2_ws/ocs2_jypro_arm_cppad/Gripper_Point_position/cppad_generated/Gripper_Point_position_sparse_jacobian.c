#include <math.h>
#include <stdio.h>

typedef struct Array {
    void* data;
    unsigned long size;
    int sparse;
    const unsigned long* idx;
    unsigned long nnz;
} Array;

struct LangCAtomicFun {
    void* libModel;
    int (*forward)(void* libModel,
                   int atomicIndex,
                   int q,
                   int p,
                   const Array tx[],
                   Array* ty);
    int (*reverse)(void* libModel,
                   int atomicIndex,
                   int p,
                   const Array tx[],
                   Array* px,
                   const Array py[]);
};

void Gripper_Point_position_sparse_jacobian(double const *const * in,
                                            double*const * out,
                                            struct LangCAtomicFun atomicFun) {
   //independent variables
   const double* x = in[0];

   //dependent variables
   double* jac = out[0];

   // auxiliary variables
   double v[49];

   v[0] = cos(x[28]);
   v[1] = sin(x[28]);
   v[2] = 0 - v[1];
   v[3] = 0.00366 * v[0] + 0.10424 * v[2];
   v[4] = cos(x[27]);
   v[5] = sin(x[27]);
   v[6] = 0.065 + v[3] * v[4] + 0.01211 * v[5];
   v[7] = cos(x[26]);
   v[8] = 0.283 + 0.00366 * v[1] + 0.10424 * v[0] + 0.1121;
   v[9] = sin(x[26]);
   v[10] = 0 - v[9];
   v[11] = v[6] * v[7] + v[8] * v[10];
   v[12] = cos(x[25]);
   v[13] = 0.3315 + v[6] * v[9] + v[8] * v[7];
   v[14] = sin(x[25]);
   v[15] = 0 - v[14];
   v[16] = 0.0995 + v[11] * v[12] + v[13] * v[15] + 0.1813;
   v[17] = cos(x[11]);
   v[18] = 0 - v[5];
   v[19] = v[3] * v[18] + 0.01211 * v[4];
   v[20] = cos(x[24]);
   v[21] = v[11] * v[14] + v[13] * v[12];
   v[22] = sin(x[24]);
   v[23] = v[19] * v[20] + v[21] * v[22];
   v[24] = sin(x[11]);
   v[25] = v[16] * v[17] + v[23] * v[24];
   v[26] = sin(x[10]);
   v[27] = 0 - v[22];
   v[28] = v[19] * v[27] + v[21] * v[20];
   v[29] = cos(x[10]);
   v[30] = sin(x[9]);
   v[31] = 0 - v[23];
   v[32] = cos(x[9]);
   jac[1] = 0 - (v[25] * v[26] + v[28] * v[29]) * v[30] + (v[16] * v[24] + v[31] * v[17]) * v[32];
   v[33] = cos(x[9]);
   v[34] = sin(x[10]);
   v[35] = cos(x[10]);
   jac[2] = 0 - v[28] * v[33] * v[34] + v[25] * v[33] * v[35];
   v[28] = v[33] * v[26];
   v[25] = sin(x[9]);
   v[36] = sin(x[11]);
   v[37] = cos(x[11]);
   jac[3] = 0 - (v[16] * v[28] + v[31] * v[25]) * v[36] + (v[16] * v[25] + v[23] * v[28]) * v[37];
   v[31] = v[28] * v[24] - v[25] * v[17];
   v[23] = v[33] * v[29];
   v[16] = sin(x[24]);
   v[38] = cos(x[24]);
   jac[4] = 0 - (v[19] * v[31] + v[21] * v[23]) * v[16] + (v[21] * v[31] - v[19] * v[23]) * v[38];
   v[28] = v[28] * v[17] + v[25] * v[24];
   v[21] = v[23] * v[20] + v[31] * v[22];
   v[19] = sin(x[25]);
   v[39] = cos(x[25]);
   jac[5] = 0 - (v[11] * v[28] + v[13] * v[21]) * v[19] + (v[11] * v[21] - v[13] * v[28]) * v[39];
   v[13] = v[21] * v[14] + v[28] * v[12];
   v[21] = v[21] * v[12] + v[28] * v[15];
   v[28] = sin(x[26]);
   v[11] = cos(x[26]);
   jac[6] = 0 - (v[6] * v[13] + v[8] * v[21]) * v[28] + (v[6] * v[21] - v[8] * v[13]) * v[11];
   v[8] = v[21] * v[9] + v[13] * v[7];
   v[23] = v[23] * v[27] + v[31] * v[20];
   v[31] = sin(x[27]);
   v[6] = cos(x[27]);
   jac[7] = 0 - (v[3] * v[8] + 0.01211 * v[23]) * v[31] + (0.01211 * v[8] - v[3] * v[23]) * v[6];
   v[23] = v[23] * v[18] + v[8] * v[4];
   v[21] = v[21] * v[7] + v[13] * v[10];
   v[13] = sin(x[28]);
   v[8] = cos(x[28]);
   jac[8] = 0 - (0.00366 * v[23] + 0.10424 * v[21]) * v[13] + (0.00366 * v[21] - 0.10424 * v[23]) * v[8];
   v[21] = 0.00366 * v[0] + 0.10424 * v[2];
   v[23] = 0.065 + v[21] * v[4] + 0.01211 * v[5];
   v[3] = 0.283 + 0.00366 * v[1] + 0.10424 * v[0] + 0.1121;
   v[40] = v[23] * v[7] + v[3] * v[10];
   v[41] = 0.3315 + v[23] * v[9] + v[3] * v[7];
   v[42] = 0.0995 + v[40] * v[12] + v[41] * v[15] + 0.1813;
   v[43] = 0 - v[42];
   v[44] = v[21] * v[18] + 0.01211 * v[4];
   v[45] = v[40] * v[14] + v[41] * v[12];
   v[46] = v[44] * v[20] + v[45] * v[22];
   v[47] = v[42] * v[17] + v[46] * v[24];
   v[48] = v[44] * v[27] + v[45] * v[20];
   jac[10] = 0 - (v[43] * v[24] + v[46] * v[17]) * v[30] + (v[47] * v[26] + v[48] * v[29]) * v[32];
   jac[11] = 0 - v[48] * v[25] * v[34] + v[47] * v[25] * v[35];
   v[48] = v[25] * v[26];
   jac[12] = 0 - (v[42] * v[48] + v[46] * v[33]) * v[36] + (v[43] * v[33] + v[46] * v[48]) * v[37];
   v[46] = v[48] * v[24] + v[33] * v[17];
   v[25] = v[25] * v[29];
   jac[13] = 0 - (v[44] * v[46] + v[45] * v[25]) * v[16] + (v[45] * v[46] - v[44] * v[25]) * v[38];
   v[48] = v[48] * v[17] - v[33] * v[24];
   v[33] = v[25] * v[20] + v[46] * v[22];
   jac[14] = 0 - (v[40] * v[48] + v[41] * v[33]) * v[19] + (v[40] * v[33] - v[41] * v[48]) * v[39];
   v[41] = v[33] * v[14] + v[48] * v[12];
   v[33] = v[33] * v[12] + v[48] * v[15];
   jac[15] = 0 - (v[23] * v[41] + v[3] * v[33]) * v[28] + (v[23] * v[33] - v[3] * v[41]) * v[11];
   v[3] = v[33] * v[9] + v[41] * v[7];
   v[25] = v[25] * v[27] + v[46] * v[20];
   jac[16] = 0 - (v[21] * v[3] + 0.01211 * v[25]) * v[31] + (0.01211 * v[3] - v[21] * v[25]) * v[6];
   v[25] = v[25] * v[18] + v[3] * v[4];
   v[33] = v[33] * v[7] + v[41] * v[10];
   jac[17] = 0 - (0.00366 * v[25] + 0.10424 * v[33]) * v[13] + (0.00366 * v[33] - 0.10424 * v[25]) * v[8];
   v[2] = 0.00366 * v[0] + 0.10424 * v[2];
   v[5] = 0.065 + v[2] * v[4] + 0.01211 * v[5];
   v[1] = 0.283 + 0.00366 * v[1] + 0.10424 * v[0] + 0.1121;
   v[0] = v[5] * v[7] + v[1] * v[10];
   v[33] = 0.3315 + v[5] * v[9] + v[1] * v[7];
   v[25] = 0.0995 + v[0] * v[12] + v[33] * v[15] + 0.1813;
   v[41] = v[2] * v[18] + 0.01211 * v[4];
   v[3] = v[0] * v[14] + v[33] * v[12];
   v[21] = v[41] * v[20] + v[3] * v[22];
   jac[19] = 0 - (v[25] * v[17] + v[21] * v[24]) * v[34] + (0 - (v[41] * v[27] + v[3] * v[20])) * v[35];
   jac[20] = 0 - v[25] * v[29] * v[36] + v[21] * v[29] * v[37];
   v[24] = v[29] * v[24];
   v[26] = 0 - v[26];
   jac[21] = 0 - (v[41] * v[24] + v[3] * v[26]) * v[16] + (v[3] * v[24] - v[41] * v[26]) * v[38];
   v[29] = v[29] * v[17];
   v[22] = v[26] * v[20] + v[24] * v[22];
   jac[22] = 0 - (v[0] * v[29] + v[33] * v[22]) * v[19] + (v[0] * v[22] - v[33] * v[29]) * v[39];
   v[14] = v[22] * v[14] + v[29] * v[12];
   v[22] = v[22] * v[12] + v[29] * v[15];
   jac[23] = 0 - (v[5] * v[14] + v[1] * v[22]) * v[28] + (v[5] * v[22] - v[1] * v[14]) * v[11];
   v[9] = v[22] * v[9] + v[14] * v[7];
   v[26] = v[26] * v[27] + v[24] * v[20];
   jac[24] = 0 - (v[2] * v[9] + 0.01211 * v[26]) * v[31] + (0.01211 * v[9] - v[2] * v[26]) * v[6];
   v[26] = v[26] * v[18] + v[9] * v[4];
   v[22] = v[22] * v[7] + v[14] * v[10];
   jac[25] = 0 - (0.00366 * v[26] + 0.10424 * v[22]) * v[13] + (0.00366 * v[22] - 0.10424 * v[26]) * v[8];
   // dependent variables without operations
   jac[0] = 1;
   jac[9] = 1;
   jac[18] = 1;
}

