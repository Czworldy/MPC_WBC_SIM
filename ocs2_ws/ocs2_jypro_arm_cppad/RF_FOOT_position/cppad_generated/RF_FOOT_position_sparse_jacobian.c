#include <math.h>
#include <stdio.h>

typedef struct Array {
    void* data;
    unsigned long size;
    int sparse;
    const unsigned long* idx;
    unsigned long nnz;
} Array;

struct LangCAtomicFun {
    void* libModel;
    int (*forward)(void* libModel,
                   int atomicIndex,
                   int q,
                   int p,
                   const Array tx[],
                   Array* ty);
    int (*reverse)(void* libModel,
                   int atomicIndex,
                   int p,
                   const Array tx[],
                   Array* px,
                   const Array py[]);
};

void RF_FOOT_position_sparse_jacobian(double const *const * in,
                                      double*const * out,
                                      struct LangCAtomicFun atomicFun) {
   //independent variables
   const double* x = in[0];

   //dependent variables
   double* jac = out[0];

   // auxiliary variables
   double v[36];

   v[0] = cos(x[20]);
   v[1] = -0.3 + -0.33 * v[0];
   v[2] = cos(x[19]);
   v[3] = -1 * sin(x[20]);
   v[4] = -0.33 * v[3];
   v[5] = -1 * sin(x[19]);
   v[6] = 0 - v[5];
   v[7] = v[1] * v[2] + v[4] * v[6];
   v[8] = cos(x[18]);
   v[9] = -1 * sin(x[18]);
   v[10] = v[7] * v[8] + -0.12325 * v[9];
   v[11] = cos(x[11]);
   v[12] = 0 - v[9];
   v[13] = -0.08 + v[7] * v[12] + -0.12325 * v[8];
   v[14] = sin(x[11]);
   v[15] = v[10] * v[11] + v[13] * v[14];
   v[16] = sin(x[10]);
   v[17] = v[1] * v[5] + v[4] * v[2];
   v[18] = -1 * -1 * (1 - v[8]) + v[8];
   v[19] = 0.292 + v[17] * v[18];
   v[20] = cos(x[10]);
   v[21] = sin(x[9]);
   v[22] = 0 - v[13];
   v[23] = cos(x[9]);
   jac[1] = 0 - (v[15] * v[16] + v[19] * v[20]) * v[21] + (v[10] * v[14] + v[22] * v[11]) * v[23];
   v[24] = cos(x[9]);
   v[25] = sin(x[10]);
   v[26] = cos(x[10]);
   jac[2] = 0 - v[19] * v[24] * v[25] + v[15] * v[24] * v[26];
   v[19] = v[24] * v[16];
   v[15] = sin(x[9]);
   v[27] = sin(x[11]);
   v[28] = cos(x[11]);
   jac[3] = 0 - (v[10] * v[19] + v[22] * v[15]) * v[27] + (v[10] * v[15] + v[13] * v[19]) * v[28];
   v[22] = v[19] * v[11] + v[15] * v[14];
   v[19] = v[19] * v[14] - v[15] * v[11];
   v[13] = v[24] * v[20];
   v[17] = v[17] * v[13];
   v[10] = sin(x[18]);
   v[29] = cos(x[18]);
   jac[4] = 0 - (v[7] * v[22] + -0.12325 * v[19] + v[17] - v[17] * -1 * -1) * v[10] + (-0.12325 * v[22] - v[7] * v[19]) * -1 * v[29];
   v[19] = v[19] * v[12] + v[22] * v[8];
   v[13] = v[13] * v[18];
   v[22] = sin(x[19]);
   v[17] = cos(x[19]);
   jac[5] = 0 - (v[1] * v[19] + v[4] * v[13]) * v[22] + (v[1] * v[13] - v[4] * v[19]) * -1 * v[17];
   v[4] = sin(x[20]);
   v[1] = cos(x[20]);
   jac[6] = 0 - -0.33 * (v[13] * v[5] + v[19] * v[2]) * v[4] + -0.33 * (v[13] * v[2] + v[19] * v[6]) * -1 * v[1];
   v[13] = -0.3 + -0.33 * v[0];
   v[19] = -0.33 * v[3];
   v[7] = v[13] * v[2] + v[19] * v[6];
   v[30] = v[7] * v[8] + -0.12325 * v[9];
   v[31] = 0 - v[30];
   v[32] = -0.08 + v[7] * v[12] + -0.12325 * v[8];
   v[33] = v[30] * v[11] + v[32] * v[14];
   v[34] = v[13] * v[5] + v[19] * v[2];
   v[35] = 0.292 + v[34] * v[18];
   jac[8] = 0 - (v[31] * v[14] + v[32] * v[11]) * v[21] + (v[33] * v[16] + v[35] * v[20]) * v[23];
   jac[9] = 0 - v[35] * v[15] * v[25] + v[33] * v[15] * v[26];
   v[35] = v[15] * v[16];
   jac[10] = 0 - (v[30] * v[35] + v[32] * v[24]) * v[27] + (v[31] * v[24] + v[32] * v[35]) * v[28];
   v[32] = v[35] * v[11] - v[24] * v[14];
   v[35] = v[35] * v[14] + v[24] * v[11];
   v[15] = v[15] * v[20];
   v[34] = v[34] * v[15];
   jac[11] = 0 - (v[7] * v[32] + -0.12325 * v[35] + v[34] - v[34] * -1 * -1) * v[10] + (-0.12325 * v[32] - v[7] * v[35]) * -1 * v[29];
   v[35] = v[35] * v[12] + v[32] * v[8];
   v[15] = v[15] * v[18];
   jac[12] = 0 - (v[13] * v[35] + v[19] * v[15]) * v[22] + (v[13] * v[15] - v[19] * v[35]) * -1 * v[17];
   jac[13] = 0 - -0.33 * (v[15] * v[5] + v[35] * v[2]) * v[4] + -0.33 * (v[15] * v[2] + v[35] * v[6]) * -1 * v[1];
   v[0] = -0.3 + -0.33 * v[0];
   v[3] = -0.33 * v[3];
   v[15] = v[0] * v[2] + v[3] * v[6];
   v[9] = v[15] * v[8] + -0.12325 * v[9];
   v[35] = -0.08 + v[15] * v[12] + -0.12325 * v[8];
   v[19] = v[0] * v[5] + v[3] * v[2];
   jac[15] = 0 - (v[9] * v[11] + v[35] * v[14]) * v[25] + (0 - (0.292 + v[19] * v[18])) * v[26];
   jac[16] = 0 - v[9] * v[20] * v[27] + v[35] * v[20] * v[28];
   v[11] = v[20] * v[11];
   v[20] = v[20] * v[14];
   v[16] = 0 - v[16];
   v[19] = v[19] * v[16];
   jac[17] = 0 - (v[15] * v[11] + -0.12325 * v[20] + v[19] - v[19] * -1 * -1) * v[10] + (-0.12325 * v[11] - v[15] * v[20]) * -1 * v[29];
   v[20] = v[20] * v[12] + v[11] * v[8];
   v[16] = v[16] * v[18];
   jac[18] = 0 - (v[0] * v[20] + v[3] * v[16]) * v[22] + (v[0] * v[16] - v[3] * v[20]) * -1 * v[17];
   jac[19] = 0 - -0.33 * (v[16] * v[5] + v[20] * v[2]) * v[4] + -0.33 * (v[16] * v[2] + v[20] * v[6]) * -1 * v[1];
   // dependent variables without operations
   jac[0] = 1;
   jac[7] = 1;
   jac[14] = 1;
}

